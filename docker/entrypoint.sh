#!/usr/bin/env bash
set -euo pipefail

log() { printf '[entrypoint] %s\n' "$*" >&2; }

CONFIG_DIRS=(/config /config/claude /config/paseo /config/gh /config/git /config/jj
  /config/shell /config/shell/bashrc.d /config/ssh)
CACHE_DIRS=(/cache /cache/go /cache/go/pkg /cache/go/pkg/mod /cache/go/build /cache/go/bin
  /cache/cargo /cache/uv /cache/uv/python /cache/npm /cache/fnm
  /cache/fnm/node-versions /cache/fnm/aliases /cache/npm-global /cache/tools /cache/paseo-models)

WORKSPACE="${WORKSPACE:-/workspace}"
RUN_DIR="${HARNESS_RUN_DIR:-/run/harness}"

as_code() { gosu code "$@"; }

# https://host:port/path -> host
url_host() {
  local h="${1#*://}"
  h="${h%%/*}"
  h="${h##*@}"
  echo "${h%:*}"
}

# User-facing .env names -> Paseo env. An empty PASEO_SERVICE_PROXY_PUBLIC_BASE_URL
# makes the daemon exit (new URL("")), so it is only exported when set.
map_paseo_env() {
  local hosts=""
  [ -n "${PUBLIC_URL:-}" ] && hosts="$(url_host "$PUBLIC_URL")"
  if [ -n "${SERVICE_BASE_URL:-}" ]; then
    export PASEO_SERVICE_PROXY_PUBLIC_BASE_URL="$SERVICE_BASE_URL"
    hosts="${hosts:+$hosts,}.$(url_host "$SERVICE_BASE_URL")"
  else
    unset PASEO_SERVICE_PROXY_PUBLIC_BASE_URL
  fi
  if [ -n "$hosts" ] && [ -z "${PASEO_HOSTNAMES:-}" ]; then
    export PASEO_HOSTNAMES="$hosts"
  fi
  if [ -n "${TRUSTED_PROXIES:-}" ]; then
    export PASEO_TRUSTED_PROXIES="$TRUSTED_PROXIES"
  fi
}

root_half() {
  local puid="${PUID:-1000}" pgid="${PGID:-1000}"

  if [ "$(id -g code)" != "$pgid" ]; then
    log "remapping group code to gid $pgid"
    groupmod -o -g "$pgid" code
    usermod -g "$pgid" code
  fi
  if [ "$(id -u code)" != "$puid" ]; then
    log "remapping user code to uid $puid"
    usermod -o -u "$puid" code
  fi

  local d
  for d in "${CONFIG_DIRS[@]}" "${CACHE_DIRS[@]}"; do
    mkdir -p "$d"
    if ! as_code test -w "$d"; then
      log "chown -R $puid:$pgid $d"
      chown -R "$puid:$pgid" "$d"
    fi
  done
  # built as uid 1000; once per container, the chown persists in its layer
  for d in /opt/rustup /opt/cargo; do
    if [ -d "$d" ] && [ "$(stat -c %u "$d")" != "$puid" ]; then
      log "chown -R $puid:$pgid $d"
      chown -R "$puid:$pgid" "$d"
    fi
  done
  mkdir -p "$RUN_DIR"
  chown "$puid:$pgid" "$RUN_DIR"
  chmod 0700 "$RUN_DIR"

  if [ ! -d "$WORKSPACE" ]; then
    if mkdir -p "$WORKSPACE" 2>/dev/null; then
      chown "$puid:$pgid" "$WORKSPACE"
    else
      log "warning: workspace $WORKSPACE does not exist and cannot be created"
    fi
  elif [ "$(stat -c %u "$WORKSPACE")" = 0 ] && [ -z "$(ls -A "$WORKSPACE")" ]; then
    # fresh named volume; never touch a populated bind mount
    chown "$puid:$pgid" "$WORKSPACE"
  elif ! as_code test -w "$WORKSPACE"; then
    log "warning: workspace $WORKSPACE not writable by uid $puid; fix ownership on the host"
  fi

  [ "${KEYRING:-0}" = 1 ] && prepare_keyring_env "$puid" "$pgid"
  write_profile_env
  [ -n "${SSH_KEYS_FROM_GITHUB:-}" ] && fetch_github_keys "$SSH_KEYS_FROM_GITHUB"
  [ "${SSHD:-0}" = 1 ] && start_sshd

  exec gosu code "$0" "$@"
}

# ssh sessions do not inherit the container env. Login shells source the
# profile.d file; sshd applies ~/.ssh/environment to every session type.
# Both are world-readable or on the config volume: PASEO_PASSWORD goes to
# $RUN_DIR/env instead.
HARNESS_ENV_VARS=(WORKSPACE PUBLIC_URL TZ NODE_VERSION CLAUDE_CONFIG_DIR GH_CONFIG_DIR
  GIT_CONFIG_GLOBAL JJ_CONFIG HISTFILE GOPATH GOMODCACHE GOCACHE CARGO_HOME
  RUSTUP_HOME UV_CACHE_DIR UV_PYTHON_INSTALL_DIR NPM_CONFIG_CACHE
  NPM_CONFIG_PREFIX NPM_CONFIG_UPDATE_NOTIFIER FNM_DIR CHROME_PATH
  PUPPETEER_SKIP_DOWNLOAD PLAYWRIGHT_SKIP_BROWSER_DOWNLOAD
  DISABLE_TELEMETRY DISABLE_ERROR_REPORTING CLAUDE_CODE_DISABLE_NONESSENTIAL_TRAFFIC
  DISABLE_AUTOUPDATER DO_NOT_TRACK
  PASEO_HOME PASEO_LISTEN PASEO_RELAY_ENABLED PASEO_WEB_UI_ENABLED PASEO_LOCAL_MODELS_DIR
  PASEO_TRUSTED_PROXIES PASEO_HOSTNAMES PASEO_SERVICE_PROXY_PUBLIC_BASE_URL
  UPDATE_CHANNEL UPDATE_TOOLS UPDATE_MIN_AGE UPDATE_INTERVAL UPDATE_TIMEOUT UPDATE_START_BUDGET
  PIN_PASEO PIN_CLAUDE PIN_PLAYWRIGHT_MCP PIN_CHROME_DEVTOOLS_MCP
  XDG_RUNTIME_DIR DBUS_SESSION_BUS_ADDRESS)

write_profile_env() {
  local v
  {
    echo '# generated by entrypoint'
    for v in "${HARNESS_ENV_VARS[@]}"; do
      [ -n "${!v:-}" ] && printf 'export %s=%q\n' "$v" "${!v}"
    done
  } > /etc/profile.d/harness-env.sh
  {
    for v in "${HARNESS_ENV_VARS[@]}" PATH; do
      [ -n "${!v:-}" ] && printf '%s=%s\n' "$v" "${!v}"
    done
  } > /config/ssh/environment
  chown "${PUID:-1000}:${PGID:-1000}" /config/ssh/environment
}

# keeps the last good copy when GitHub is unreachable
fetch_github_keys() {
  local dest=/config/ssh/authorized_keys.github tmp
  tmp="$(mktemp)"
  if curl -fsS --max-time 15 "https://github.com/$1.keys" -o "$tmp" && [ -s "$tmp" ]; then
    install -m 0600 -o "${PUID:-1000}" -g "${PGID:-1000}" "$tmp" "$dest"
    log "ssh keys for github user $1 written to $dest"
  else
    log "warning: could not fetch ssh keys for github user $1"
  fi
  rm -f "$tmp"
}

start_sshd() {
  local keys=/config/ssh/host_keys
  mkdir -p "$keys" /run/sshd
  [ -f "$keys/ssh_host_ed25519_key" ] || ssh-keygen -q -t ed25519 -N '' -f "$keys/ssh_host_ed25519_key"
  chmod 0600 "$keys/ssh_host_ed25519_key"
  touch /config/ssh/authorized_keys
  chown "${PUID:-1000}:${PGID:-1000}" /config/ssh/authorized_keys
  chmod 0600 /config/ssh/authorized_keys
  if /usr/sbin/sshd -t -f /etc/ssh/sshd_harness.conf; then
    /usr/sbin/sshd -f /etc/ssh/sshd_harness.conf
    log "sshd listening on 22 (user code, keys from /config/ssh/authorized_keys*)"
  else
    log "warning: sshd config test failed, not starting sshd"
  fi
}

# Fixed bus address so ssh sessions and docker exec login shells can find it.
prepare_keyring_env() {
  export XDG_RUNTIME_DIR="/run/user/$1"
  export DBUS_SESSION_BUS_ADDRESS="unix:path=$XDG_RUNTIME_DIR/bus"
  mkdir -p "$XDG_RUNTIME_DIR"
  chown "$1:$2" "$XDG_RUNTIME_DIR"
  chmod 0700 "$XDG_RUNTIME_DIR"
}

# Throwaway keyring, unlocked for the container's lifetime. An empty password
# skips creating the login collection, so use a fixed one.
start_keyring() {
  export XDG_RUNTIME_DIR="${XDG_RUNTIME_DIR:-/tmp/runtime-$(id -u)}"
  export DBUS_SESSION_BUS_ADDRESS="${DBUS_SESSION_BUS_ADDRESS:-unix:path=$XDG_RUNTIME_DIR/bus}"
  mkdir -p "$XDG_RUNTIME_DIR"
  chmod 0700 "$XDG_RUNTIME_DIR"
  # stale socket from a previous run of this container
  rm -f "${DBUS_SESSION_BUS_ADDRESS#unix:path=}"
  if ! dbus-daemon --session --address="$DBUS_SESSION_BUS_ADDRESS" --fork --nopidfile; then
    log "warning: dbus-daemon failed, keyring not available"
    unset DBUS_SESSION_BUS_ADDRESS
    return 0
  fi
  if printf harness | gnome-keyring-daemon --unlock --components=secrets >/dev/null; then
    log "Secret Service running on $DBUS_SESSION_BUS_ADDRESS (throwaway keyring)"
  else
    log "warning: gnome-keyring-daemon failed, keyring not available"
  fi
}

link_ssh() {
  chmod 0700 /config/ssh
  if [ -L "$HOME/.ssh" ]; then
    ln -sfn /config/ssh "$HOME/.ssh"
  elif [ -d "$HOME/.ssh" ]; then
    rmdir "$HOME/.ssh" 2>/dev/null || { log "warning: $HOME/.ssh is a non-empty dir, not linking /config/ssh"; return 0; }
    ln -s /config/ssh "$HOME/.ssh"
  else
    ln -sfn /config/ssh "$HOME/.ssh"
  fi
}

link_fnm_node() {
  local fnm_dir="${FNM_DIR:-/cache/fnm}" node_version="${NODE_VERSION:-}" inst
  if [ -z "$node_version" ]; then
    node_version="$(node --version 2>/dev/null || true)"
    node_version="${node_version#v}"
  fi
  if [ -z "$node_version" ]; then
    log "warning: cannot determine image Node version, skipping fnm link"
    return 0
  fi

  mkdir -p "$fnm_dir/node-versions" "$fnm_dir/aliases"
  for inst in "$fnm_dir"/node-versions/*/installation; do
    if [ -L "$inst" ] && [ ! -e "$inst" ]; then
      rm -f "$inst"
      rmdir "$(dirname "$inst")" 2>/dev/null || true
    fi
  done

  inst="$fnm_dir/node-versions/v$node_version/installation"
  mkdir -p "$(dirname "$inst")"
  if [ -L "$inst" ] || [ ! -e "$inst" ]; then
    ln -sfn "/opt/node/v$node_version/installation" "$inst"
  fi

  # -e follows the link, so a default pointing at a removed version counts as missing
  if [ ! -e "$fnm_dir/aliases/default" ] && command -v fnm >/dev/null; then
    rm -f "$fnm_dir/aliases/default"
    fnm default "$node_version" >/dev/null || log "warning: fnm default $node_version failed"
  fi
}

# A hash saved by `paseo daemon set-password` also passes.
check_password() {
  [ -n "${PASEO_PASSWORD:-}" ] && return 0
  if [ "$(paseo daemon config get daemon.auth.password | jq -r .set)" = true ]; then
    log "using the password hash in $PASEO_HOME/config.json"
    return 0
  fi
  if [ "${ALLOW_NO_PASSWORD:-0}" = 1 ]; then
    log "warning: ALLOW_NO_PASSWORD=1, the daemon accepts any client that can reach it"
    return 0
  fi
  log "no daemon password: set PASEO_PASSWORD in .env, or ALLOW_NO_PASSWORD=1 on a trusted network"
  return 1
}

set_worktrees_root() {
  local want="$WORKSPACE/.worktrees" got
  paseo daemon config set worktrees.root "$want" --string >/dev/null ||
    log "warning: paseo daemon config set worktrees.root failed"
  got="$(paseo daemon config get worktrees.root | jq -r '.value // empty')" || true
  [ "$got" = "$want" ] || log "warning: worktrees.root is '$got', expected '$want'"
}

# sourced by .bashrc and the helpers, so ssh and docker exec shells can reach the daemon
write_run_env() {
  local f="$RUN_DIR/env"
  rm -f "$f"
  [ -n "${PASEO_PASSWORD:-}" ] || return 0
  (umask 077; printf 'export PASEO_PASSWORD=%q\n' "$PASEO_PASSWORD" > "$f")
}

# update takes $RUN_DIR/update.lock itself; the timeout keeps a stuck update from blocking boot
start_update() {
  command -v update >/dev/null || return 0
  timeout "$(( ${UPDATE_START_BUDGET:-180} + 60 ))" update --once ||
    log "update --once failed or timed out; using the installed versions"
  update --prune || log "update --prune failed"
}

user_half() {
  # covers --user runs where the root half never ran
  mkdir -p "${CONFIG_DIRS[@]}" "${CACHE_DIRS[@]}" "$RUN_DIR" 2>/dev/null || true
  link_ssh
  mkdir -p "$(dirname "${GIT_CONFIG_GLOBAL:-/config/git/config}")"
  touch "${GIT_CONFIG_GLOBAL:-/config/git/config}"

  link_fnm_node
  [ "${KEYRING:-0}" = 1 ] && start_keyring

  if [ "${1:-}" = serve ]; then
    check_password || exit 1
    set_worktrees_root
    register-mcp || log "register-mcp failed; run it manually later"
    start_update
    write_run_env
    # left by a killed container; a recycled pid would make the daemon refuse to start
    rm -f "$PASEO_HOME/paseo.pid" "$RUN_DIR/daemon.pid" "$RUN_DIR/restart"
    exec harness-run
  fi
  exec "$@"
}

map_paseo_env
if [ "$(id -u)" = 0 ]; then
  root_half "$@"
fi
user_half "$@"
